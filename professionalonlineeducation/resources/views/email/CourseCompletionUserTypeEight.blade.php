<h1 style="color: #0AACFA; font-size: 30px;">Registration Steps</h1>
<p><b style="color: #0AACFA; font-size: 24px;">Step 1: Complete All CA Course Sections </b></p>
<p>
    If you were enrolled in CAT01 you may be done, but, because this could also be a partial course, you will need to verify if your chiropractor has a specialty license in PMMTP (you will need to complete CAT02) , or if your doctor has a specialty license in Acupuncture (you will need to register and complete CAT03) to meet your CA requirements in Arizona.  If he does not have any specialty licenses, congratulations You are good to proceed to the next step.
</p>

<p><b style="color: #0AACFA; font-size: 24px;">Step 2: Complete CPR </b></p>
<p>
