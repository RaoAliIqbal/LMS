</p>


<p><b style="color: #0AACFA; font-size: 24px;">Step 3: Register  </b></p>
<p>As you learned in the course, you will need to register with the Arizona Board of Chiropractic Examiners. Go to  <a href="https://chiroboard.az.gov/chiropractic%20assistants/">https://chiroboard.az.gov/chiropractic assistants/</a> </p>
<p>Scroll down page and click on registration/transfer form, fill out pdf online, and upload picture of CPR card.  Print a copy of form before submitting, </p>


<p><b style="color: #0AACFA; font-size: 24px;">Step 4: Make Copies   </b></p>
<p>Make several copies.  It is required that you keep a copy of your registration in your employment file at work.  However, it is a good rule of thumb to make a copy of both your registration documents, CPR card and your certificate and keep that in your personal files.</p>


